/// Test catalog for checking how the player handles different video shapes.
///
/// Sizes are the dimensions each file is encoded at (for the anamorphic and
/// rotated patterns, the size it should *display* at). On 2026-10-26 every
/// network source answered HTTP 200 with the expected codec and size, but none
/// has been played on a device yet; public test servers can change.
library;

/// One playable entry: either a Chorki API route or a direct URL / asset.
class TestVideo {
  const TestVideo.route({
    required this.title,
    required String this.route,
    this.note = '',
  }) : url = null,
       ratio = 'from API',
       width = 0,
       height = 0,
       credit = '',
       headers = const {},
       androidOnly = false;

  const TestVideo.url({
    required this.title,
    required this.ratio,
    required this.width,
    required this.height,
    required String this.url,
    this.note = '',
    this.credit = '',
    this.headers = const {},
    this.androidOnly = false,
  }) : route = null;

  final String title;

  /// Intended display shape, e.g. `9:16`.
  final String ratio;

  /// Expected display size in pixels; 0 when unknown (API routes).
  final int width;
  final int height;

  final String? route;

  /// Network URL, or `asset:` URI for a bundled pattern.
  final String? url;

  final String note;

  /// License / source attribution.
  final String credit;

  final Map<String, String> headers;

  /// VP9 WebM: iOS cannot decode it.
  final bool androidOnly;

  bool get hasSize => width > 0 && height > 0;

  String get sizeLabel => hasSize ? '$width×$height' : '';
}

class TestVideoGroup {
  const TestVideoGroup(this.title, this.description, this.videos);

  final String title;
  final String description;
  final List<TestVideo> videos;
}


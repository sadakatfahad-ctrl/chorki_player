/// `Data:` keys documented on each enum value, by value name.
Map<String, Set<String>> documentedKeys(SourceFile events) {
  final decl = events.unit.declarations.whereType<EnumDeclaration>().firstWhere(
    (e) => e.namePart.typeName.lexeme == 'ChorkiAnalyticsEventType',
  );
  final out = <String, Set<String>>{};
  decl.accept(_EnumDocs(out));
  return out;
}

class _EnumDocs extends RecursiveAstVisitor<void> {
  _EnumDocs(this.out);
  final Map<String, Set<String>> out;

  @override
  void visitEnumConstantDeclaration(EnumConstantDeclaration node) {
    {
      final doc =
          node.documentationComment?.tokens
              .map((t) => t.lexeme.replaceFirst(RegExp(r'^///\s?'), ''))
              .join(' ') ??
          '';
      final data = RegExp(r'Data:(.*)$').firstMatch(doc)?[1] ?? '';
      // Keys before "+ the ad context" / "the ad context".
      final own = data.split(RegExp(r'\+|the ad context')).first;
      out[node.name.lexeme] = {
        for (final m in RegExp('`(\\w+)`').allMatches(own)) m[1]!,
      };
    }
  }
}

/// Markdown table of the schema, embedded in README.md between markers.
String schemaTable() {
  final rows = StringBuffer()
    ..writeln('| Event | Category | Data keys |')
    ..writeln('|---|---|---|');
  for (final type in ChorkiAnalyticsEventType.values) {
    final keys = [
      for (final f in ChorkiAnalyticsSchema.own(type))
        f.required ? '`${f.key}`' : '`${f.key}`?',
      if (type.category == ChorkiAnalyticsCategory.ad) '*ad context*',
    ];
    rows.writeln(
      '| `${type.name}` | ${type.category.name} | '
      '${keys.isEmpty ? '–' : keys.join(', ')} |',
    );
  }
  return rows.toString();
}

const _start = '<!-- analytics-schema:start (generated by test/guardrails) -->';
const _end = '<!-- analytics-schema:end -->';

void main() {
  test('fixture: Data lines are parsed', () {
    final f = SourceFile('lib/x.dart', '''
enum ChorkiAnalyticsEventType {
  /// Something.
  ///
  /// Data: `a`, `b`.
  one(1),
  /// Data: `c` + the ad context.
  two(2),
  /// Data: none.
  three(3);
  const ChorkiAnalyticsEventType(this.x);
  final int x;
}
''');
    expect(documentedKeys(f), {
      'one': {'a', 'b'},
      'two': {'c'},
      'three': <String>{},
    });
  });

  test('every event type has a schema and its doc lists exactly its keys', () {
    final docs = documentedKeys(
      SourceFile.read('lib/src/analytics/chorki_analytics_event.dart'),
    );
    final mismatches = [
      for (final type in ChorkiAnalyticsEventType.values)
        if (!_sameSet(docs[type.name] ?? {}, {
          for (final f in ChorkiAnalyticsSchema.own(type)) f.key,
        }))
          '${type.name}: doc ${docs[type.name]} vs schema '
              '${ChorkiAnalyticsSchema.own(type).map((f) => f.key).toList()}',
    ];
    expect(mismatches, isEmpty);
  });

  test('every schema key is a ChorkiAnalyticsKeys constant', () {
    final keysFile = File(
      'lib/src/analytics/chorki_analytics_schema.dart',
    ).readAsStringSync();
    final constants = RegExp(
      r"static const (\w+) = '(\w+)';",
    ).allMatches(keysFile).map((m) => (m[1], m[2])).toList();
    expect(
      constants.every((c) => c.$1 == c.$2),
      isTrue,
      reason: 'constant name == value',
    );
    final names = {for (final c in constants) c.$1};
    for (final type in ChorkiAnalyticsEventType.values) {
      for (final f in ChorkiAnalyticsSchema.of(type)) {
        expect(names, contains(f.key), reason: type.name);
      }
    }
  });

  test('the schema validator catches unknown, missing and mistyped keys', () {
    expect(
      ChorkiAnalyticsSchema.validate(ChorkiAnalyticsEventType.seek, {
        'fromMs': 1,
        'toMs': '2',
        'oops': true,
      }),
      [
        'seek: unknown key "oops"',
        'seek: "toMs" should be integer, got String',
        'seek: missing "source"',
      ],
    );
    expect(
      ChorkiAnalyticsSchema.validate(ChorkiAnalyticsEventType.adQuartile, {
        'percent': 25,
        'breakIndex': 0,
        'adId': 'x',
      }),
      isEmpty,
    );
  });

  test('every event type has a Matomo description', () {
    for (final type in ChorkiAnalyticsEventType.values) {
      final event = ChorkiAnalyticsEvent(
        type: type,
        sessionId: 's',
        timestamp: DateTime(2026),
        metadata: const ChorkiMediaMetadata(title: 't'),
        position: Duration.zero,
        duration: Duration.zero,
        watchedTime: Duration.zero,
      );
      final (category, action, _, _) = MatomoRequestBuilder.describe(event);
      expect(category, isNotEmpty, reason: type.name);
      expect(action, isNotEmpty, reason: type.name);
    }
  });

  test('the README event table is generated from the schema', () {
    final readme = File('README.md');
    final text = readme.readAsStringSync();
    final start = text.indexOf(_start);
    final end = text.indexOf(_end);
    final table = schemaTable();
    if (start >= 0 && end > start) {
      final current = text.substring(start + _start.length, end).trim();
      if (current == table.trim()) return;
      if (updateGoldens) {
        readme.writeAsStringSync(
          '${text.substring(0, start + _start.length)}\n$table${text.substring(end)}',
        );
        return;
      }
    }
    fail(
      'README.md must contain the generated event table between\n$_start\n'
      'and\n$_end\nRun UPDATE_GOLDENS=1 flutter test test/guardrails to '
      'regenerate it (the markers must exist).',
    );
  });
}

bool _sameSet(Set<String> a, Set<String> b) =>
    a.length == b.length && a.containsAll(b);
